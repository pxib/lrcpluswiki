/* Pack whole-cell luminance for the character renderer, including offline copies. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const {deflateSync} = require('node:zlib');
const root = path.resolve(__dirname, '..');
const width = 96, height = 72, fps = 20;
const result = spawnSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-i',
  path.join(root, 'docs/manual/assets/media/bad-apple.mp4'), '-vf',
  `fps=${fps},scale=${width}:${height}:flags=area,format=gray`, '-an', '-f', 'rawvideo',
  '-pix_fmt', 'gray', 'pipe:1'], {maxBuffer: 64 * 1024 * 1024, windowsHide: true});
if (result.error) throw result.error;
if (result.status !== 0) throw new Error(result.stderr.toString());
const count = Math.floor(result.stdout.length / (width * height));
if (!count) throw new Error('No video frames were decoded');
const packed = Buffer.alloc(count * width * height / 2);
for (let index = 0; index < packed.length; index++) {
  const high = Math.round(result.stdout[index * 2] / 17);
  const low = Math.round(result.stdout[index * 2 + 1] / 17);
  packed[index] = (high << 4) | low;
}
const encoded = deflateSync(packed, {level: 9}).toString('base64');
const payload = {width, height, fps, count, deflate: encoded};
const output = '// Generated by tools/build-bad-apple-frames.cjs; four-bit luminance, two cells per byte.\n'
  + `window.ManualBadAppleFrames = ${JSON.stringify(payload)};\n`;
fs.writeFileSync(path.join(root, 'docs/manual/assets/media/bad-apple-frames.js'), output);
console.log(`Packed ${count} frames at ${width} x ${height}, ${fps} fps into ${Buffer.byteLength(output)} bytes.`);
