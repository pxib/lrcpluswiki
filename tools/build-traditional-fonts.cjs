/* Bundle the pinned Google Fonts WOFF2 subsets without a runtime network dependency. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const root = path.resolve(__dirname, '..');
const manual = path.join(root, 'docs/manual');
const source = path.join(root, 'tools/font-sources/LXGWWenKaiTC-google.css');
const manifestFile = path.join(root, 'tools/font-sources/LXGWWenKaiTC-files.json');
const stylesheet = path.join(manual, 'traditional-fonts.css');
const download = process.argv.includes('--download');
const check = process.argv.includes('--check');
const hash = data => createHash('sha256').update(data).digest('hex');
async function main() {
  const manifest = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, 'utf8')) : {};
  const files = [];
  const css = fs.readFileSync(source, 'utf8').replace(/@font-face\s*\{[^}]+\}/g, face => {
    const url = face.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/)?.[1];
    const weight = face.match(/font-weight:\s*(\d+)/)?.[1];
    if (!url || !['400', '700'].includes(weight)) throw new Error('Unexpected Google Fonts face');
    const name = `LXGWWenKaiTC-${weight}-${hash(url).slice(0, 12)}.woff2`;
    files.push({url, name});
    return face.replace(`url(${url})`, `url('assets/fonts/${name}')`);
  });
  if (!files.length || files.length !== new Set(files.map(file => file.name)).size) throw new Error('Missing or duplicate font subsets');
  let completed = 0, bytes = 0;
  async function worker() {
    while (completed < files.length) {
      const {url, name} = files[completed++];
      const target = path.join(manual, 'assets/fonts', name);
      if (!fs.existsSync(target) && download && !check) {
        const response = await fetch(url);
        if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
        const data = Buffer.from(await response.arrayBuffer());
        if (data.toString('ascii', 0, 4) !== 'wOF2') throw new Error(`Invalid WOFF2: ${name}`);
        fs.writeFileSync(target, data);
      }
      const data = fs.readFileSync(target);
      if (data.toString('ascii', 0, 4) !== 'wOF2') throw new Error(`Invalid WOFF2: ${name}`);
      const digest = hash(data);
      if (manifest[name] && manifest[name] !== digest) throw new Error(`Changed font bytes: ${name}`);
      if (check && !manifest[name]) throw new Error(`Missing font checksum: ${name}`);
      manifest[name] = digest;
      bytes += data.length;
    }
  }
  await Promise.all(Array.from({length: 8}, worker));
  const style = "/* Generated by tools/build-traditional-fonts.cjs; original fonts use OFL-1.1. */\n" + css
    + '\n/* Keep the requested family throughout Traditional Chinese UI and article text. */\n'
    + 'html[lang="zh-Hant"],html[lang="zh-Hant"] :is(h1,h2,h3,a,button,input,select,.brand span,.brand strong,.talk-comment-menu){font-family:"LXGW WenKai TC","Microsoft JhengHei","PingFang TC",serif}\n';
  if (check) {
    if (fs.readFileSync(stylesheet, 'utf8') !== style) throw new Error('Traditional font CSS needs rebuilding');
  } else {
    fs.writeFileSync(stylesheet, style);
    fs.writeFileSync(manifestFile, JSON.stringify(Object.fromEntries(Object.entries(manifest).sort()), null, 2) + '\n');
  }
  console.log(`LXGW WenKai TC: ${files.length} verified WOFF2 subsets, ${bytes.toLocaleString('en')} bytes, Regular and Bold.`);
}
main().catch(error => {console.error(error); process.exitCode = 1;});
