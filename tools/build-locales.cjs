/* Offline language build. Uses the same jsdom installation as the community tests. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('../.tmp/community-check/node_modules/jsdom');
const root = path.resolve(__dirname, '../docs/manual');
const languages = [['en', 'English', 'index'], ['ja', '日本語', 'ja'], ['ko', '한국어', 'ko'], ['yue-Hant', '粵語', 'yue'], ['zh', '简体中文', 'zh'], ['cs', 'Čeština', 'cs'], ['vi', 'Tiếng Việt', 'vi']];
const ui = JSON.parse(fs.readFileSync(path.join(root, 'locales/ui.json'), 'utf8'));
const textOf = node => node.nodeValue.trim();
const check = process.argv.includes('--check');
function write(file, value) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) throw new Error(`Outdated language output: ${path.relative(root, file)}`);
  } else fs.writeFileSync(file, value);
}
function translate(document, dictionary) {
  const visit = parent => {
    for (const node of parent.childNodes) {
      if (node.nodeType === 3 && textOf(node)) {
        const value = dictionary[textOf(node)];
        if (value === undefined) throw new Error(`Missing translation: ${textOf(node)}`);
        node.nodeValue = node.nodeValue.replace(textOf(node), () => value);
      } else if (node.nodeType === 1 && !node.matches('script, style, code, kbd, pre, .language-switch, template')) {
        // Translate complete sentences together, retaining their authored inline markup.
        const html = node.innerHTML.trim();
        if (node.matches('p, li, dt, dd, td, th, figcaption') && node.children.length && !node.querySelector('p, li, ul, ol, dl, table') && dictionary[html] !== undefined) node.innerHTML = dictionary[html];
        else visit(node);
      }
    }
  };
  visit(document.documentElement);
  for (const node of document.querySelectorAll('[aria-label], [alt], [placeholder], [data-title], meta[name="description"]')) {
    if (node.closest('.language-switch')) continue;
    for (const attr of ['aria-label', 'alt', 'placeholder', 'data-title', 'content']) {
      if (!node.hasAttribute(attr)) continue;
      const value = node.getAttribute(attr);
      if (dictionary[value] === undefined) throw new Error(`Missing attribute translation: ${value}`);
      node.setAttribute(attr, dictionary[value]);
    }
  }
}
function navigation(document, lang, kind) {
  const nav = document.querySelector('.language-switch');
  nav.replaceChildren('\n', nav.querySelector('h2'), '\n');
  for (const [code, name, base] of languages) {
    const a = document.createElement('a');
    a.href = kind ? `${code === 'en' ? '' : base + '-'}${kind}.html` : `${base}.html`;
    a.lang = a.hreflang = code;
    if (code === lang) a.setAttribute('aria-current', 'true');
    a.textContent = name;
    nav.append(a, '\n');
  }
  document.querySelectorAll('link[rel="alternate"]').forEach(node => node.remove());
  if (!kind) for (const [code, , base] of languages) {
    const link = document.createElement('link');
    link.rel = 'alternate'; link.hreflang = code; link.href = `${base}.html`;
    document.head.append(link, '\n');
  }
}
const serialize = dom => dom.serialize() + '\n';
for (const [lang, , base] of languages.slice(4)) {
  const dictionary = JSON.parse(fs.readFileSync(path.join(root, `locales/${lang}.json`), 'utf8'));
  for (const key of ui) if (dictionary[key] === undefined) throw new Error(`Missing ${lang} UI translation: ${key}`);
  const runtime = Object.fromEntries(ui.map(key => [key, dictionary[key]]));
  write(path.join(root, `locales/${lang}.js`), `/* Generated by tools/build-locales.cjs. */\n'use strict';\n(() => {\n  const dictionary = ${JSON.stringify(runtime, null, 2)};\n  window.ManualLocale = Object.freeze({\n    text: value => dictionary[value] ?? value,\n    manual: '${base}.html', account: '${base}-account.html', user: '${base}-user.html'\n  });\n})();\n`);
  for (const kind of ['', 'account', 'user']) {
    const source = kind ? `${kind}.html` : 'index.html';
    const dom = new JSDOM(fs.readFileSync(path.join(root, source), 'utf8'));
    const document = dom.window.document;
    document.documentElement.lang = lang;
    // Scripted examples have their own authored languages; new editions start with live discussions.
    document.querySelectorAll('template[data-talk-for]').forEach(node => node.remove());
    translate(document, dictionary);
    document.querySelectorAll('noscript [lang="en"]').forEach(node => node.lang = lang);
    for (const a of document.querySelectorAll('a[href]')) {
      if (a.closest('.language-switch')) continue;
      a.setAttribute('href', a.getAttribute('href').replace(/^(index|account|user)\.html/, (_, page) => page === 'index' ? `${base}.html` : `${base}-${page}.html`));
    }
    const script = document.createElement('script');
    script.src = `locales/${lang}.js`;
    document.head.querySelector('script').before(script);
    navigation(document, lang, kind);
    write(path.join(root, kind ? `${base}-${kind}.html` : `${base}.html`), serialize(dom));
  }
}
for (const [lang, , base] of languages.slice(0, 4)) for (const kind of ['', 'account', 'user']) {
  const file = path.join(root, kind ? `${lang === 'en' ? '' : base + '-'}${kind}.html` : `${base}.html`);
  // Keep authored source formatting outside the language navigation and alternate links.
  let source = fs.readFileSync(file, 'utf8');
  const dom = new JSDOM(source);
  navigation(dom.window.document, lang, kind);
  source = source.replace(/<nav\b[^>]*class="language-switch"[^>]*>[\s\S]*?<\/nav>/, dom.window.document.querySelector('.language-switch').outerHTML);
  source = source.replace(/\s*<link\b[^>]*rel="alternate"[^>]*>/g, '');
  if (!kind) source = source.replace('</head>', [...dom.window.document.querySelectorAll('link[rel="alternate"]')].map(node => '  ' + node.outerHTML).join('\n') + '\n</head>');
  write(file, source);
}
console.log(check ? 'Language outputs are current.' : 'Built Chinese, Czech, and Vietnamese manuals, accounts, user pages, and language navigation.');
