/* Bundle article coverage so the language menu also works from local files. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

function buildArticleLanguages(root) {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const editions = [...read('index.html').matchAll(/<link\s+rel="alternate"\s+hreflang="([^"]+)"\s+href="([^"]+)"/g)];
  if (!editions.length) throw new Error('No manual language editions found in index.html');

  const languagesByArticle = new Map();
  for (const [, language, file] of editions) {
    const articles = new Set([...read(file).matchAll(/<article\b[^>]*?\s+id="([^"]+)"/g)].map(match => match[1]));
    if (!articles.size) throw new Error(`No manual articles found in ${file}`);
    for (const id of articles) {
      if (!languagesByArticle.has(id)) languagesByArticle.set(id, []);
      languagesByArticle.get(id).push(language);
    }
  }

  const partial = [...languagesByArticle].filter(([, languages]) => languages.length < editions.length);
  const bundle = '/* Generated by tools/build-article-languages.cjs. */\n'
    + `window.ManualArticleLanguages = new Map(${JSON.stringify(partial)});\n`;
  fs.writeFileSync(path.join(root, 'article-languages.js'), bundle);
}

if (require.main === module) buildArticleLanguages(path.resolve(__dirname, '../docs/manual'));
module.exports = {buildArticleLanguages};
